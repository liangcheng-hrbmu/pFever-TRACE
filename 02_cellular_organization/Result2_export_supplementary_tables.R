# ============================================================
# Robust Ro/e table function
# Works whether as.table output columns are Var1/Var2 or named
# ============================================================

make_roe_category <- function(x) {
  dplyr::case_when(
    is.na(x) ~ NA_character_,
    x > 3 ~ "+++",
    x > 2 ~ "++",
    x > 1 ~ "+",
    TRUE ~ "0"
  )
}

table_to_long <- function(mat, value_name) {
  df <- as.data.frame(as.table(mat), stringsAsFactors = FALSE)

  # 不管原始列名是 Var1/Var2/Freq，还是 disease/cell_population/Freq，
  # 这里都强制按位置改名，避免 rename 找不到 Var1。
  colnames(df)[1:3] <- c("disease", "cell_population", value_name)

  df
}

compute_roe_table <- function(
    df,
    cell_col,
    annotation_level,
    parent_level1_value = NA_character_,
    min_cell_per_group = 0
) {

  df2 <- df %>%
    dplyr::mutate(
      disease = as.character(disease),
      disease_group = as.character(disease_group),
      cell_population = trimws(as.character(.data[[cell_col]]))
    ) %>%
    dplyr::filter(
      !is.na(disease), disease %in% disease_order,
      !is.na(cell_population), cell_population != ""
    )

  if (nrow(df2) == 0) {
    return(tibble::tibble())
  }

  # observed counts
  obs_df <- df2 %>%
    dplyr::count(disease, disease_group, cell_population, name = "observed_count")

  mat_obs <- stats::xtabs(
    observed_count ~ disease + cell_population,
    data = obs_df
  )

  mat_obs <- as.matrix(mat_obs)

  # 固定 disease 顺序
  keep_rows <- disease_order[disease_order %in% rownames(mat_obs)]
  mat_obs <- mat_obs[keep_rows, , drop = FALSE]

  if (nrow(mat_obs) == 0 || ncol(mat_obs) == 0) {
    return(tibble::tibble())
  }

  # 用于 Ro/e 计算的矩阵
  mat_for_roe <- mat_obs

  if (min_cell_per_group > 0) {
    mat_for_roe[mat_for_roe < min_cell_per_group] <- NA
  }

  row_total <- rowSums(mat_for_roe, na.rm = TRUE)
  col_total <- colSums(mat_for_roe, na.rm = TRUE)
  grand_total <- sum(mat_for_roe, na.rm = TRUE)

  if (!is.finite(grand_total) || grand_total <= 0) {
    expected <- mat_for_roe
    expected[,] <- NA_real_
    roe <- mat_for_roe
    roe[,] <- NA_real_
  } else {
    expected <- outer(row_total, col_total, FUN = "*") / grand_total
    rownames(expected) <- rownames(mat_for_roe)
    colnames(expected) <- colnames(mat_for_roe)

    roe <- mat_for_roe / expected
    roe[!is.finite(roe)] <- NA
  }

  obs_long <- table_to_long(mat_obs, "observed_count")
  expected_long <- table_to_long(expected, "expected_count")
  roe_long <- table_to_long(roe, "roe")

  disease_group_df <- df2 %>%
    dplyr::distinct(disease, disease_group) %>%
    dplyr::mutate(
      disease = as.character(disease),
      disease_group = as.character(disease_group)
    )

  out <- obs_long %>%
    dplyr::left_join(
      expected_long,
      by = c("disease", "cell_population")
    ) %>%
    dplyr::left_join(
      roe_long,
      by = c("disease", "cell_population")
    ) %>%
    dplyr::left_join(
      disease_group_df,
      by = "disease"
    ) %>%
    dplyr::mutate(
      annotation_level = annotation_level,
      parent_Level1 = parent_level1_value,
      roe_category = make_roe_category(roe),
      symbol = roe_category,
      included_for_roe = !is.na(roe)
    ) %>%
    dplyr::select(
      disease,
      disease_group,
      annotation_level,
      parent_Level1,
      cell_population,
      observed_count,
      expected_count,
      roe,
      roe_category,
      symbol,
      included_for_roe
    ) %>%
    dplyr::arrange(
      factor(disease, levels = disease_order),
      annotation_level,
      parent_Level1,
      cell_population
    )

  return(out)
}

