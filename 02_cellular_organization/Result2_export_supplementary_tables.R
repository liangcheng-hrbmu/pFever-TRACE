  dplyr::left_join(expected_long, by = c("disease", "Cellular_module")) %>%
  dplyr::left_join(roe_long, by = c("disease", "Cellular_module")) %>%
  dplyr::left_join(disease_group_df, by = "disease") %>%
  dplyr::left_join(dominant_cm_df, by = "disease") %>%
  dplyr::mutate(
    roe_category = make_roe_category(roe),
    symbol = roe_category
  ) %>%
  dplyr::select(
    Cellular_module,
    disease,
    disease_group,
    n_samples,
    mean_CM_abundance,
    expected_value,
    roe,
    roe_category,
    symbol,
    dominant_CM_by_roe
  ) %>%
  dplyr::arrange(
    Cellular_module,
    factor(disease, levels = disease_order)
  )

