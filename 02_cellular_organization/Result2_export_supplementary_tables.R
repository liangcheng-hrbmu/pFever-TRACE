  dplyr::group_by(Cellular_module) %>%
  dplyr::arrange(dplyr::desc(module_weight), .by_group = TRUE) %>%
  dplyr::mutate(
    rank_within_module = dplyr::row_number(),
    shown_in_main_figure = rank_within_module <= 10
  ) %>%
  dplyr::ungroup() %>%
  dplyr::select(
    Cellular_module,
    Level2_population,
    Parent_Level1,
    module_weight,
    rank_within_module,
    shown_in_main_figure
  )

