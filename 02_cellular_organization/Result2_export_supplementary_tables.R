h <- tryCatch(
  NMF::scoef(NMF_K4),
  error = function(e) NMF::coef(NMF_K4)
)

h <- as.matrix(h)

if (nrow(h) == 4) {
  rownames(h) <- sprintf("CM%02d", 1:4)
} else if (ncol(h) == 4) {
  h <- t(h)
  rownames(h) <- sprintf("CM%02d", 1:4)
} else {
  stop("h matrix does not look like CM x sample. Current dim: ",
       paste(dim(h), collapse = " x "))
}

sample_meta <- meta_use %>%
  dplyr::select(sampleID, disease, disease_group) %>%
  dplyr::distinct(sampleID, .keep_all = TRUE) %>%
  as.data.frame()

rownames(sample_meta) <- sample_meta$sampleID

common_samples <- intersect(colnames(h), rownames(sample_meta))
h <- h[, common_samples, drop = FALSE]
sample_meta <- sample_meta[common_samples, , drop = FALSE]

stopifnot(all(colnames(h) == rownames(sample_meta)))

cm_names <- rownames(h)

sample_cm_df <- as.data.frame(t(h)) %>%
  tibble::rownames_to_column("sampleID") %>%
  dplyr::left_join(
    sample_meta %>%
      dplyr::mutate(sampleID = rownames(sample_meta)) %>%
      dplyr::select(sampleID, disease, disease_group),
    by = "sampleID"
  ) %>%
  dplyr::filter(!is.na(disease), disease %in% disease_order)

mean_cm_by_disease <- sample_cm_df %>%
  dplyr::group_by(disease, disease_group) %>%
  dplyr::summarise(
    dplyr::across(dplyr::all_of(cm_names), ~ mean(.x, na.rm = TRUE)),
    n_samples = dplyr::n(),
    .groups = "drop"
  )

mean_mat <- mean_cm_by_disease %>%
  dplyr::select(disease, dplyr::all_of(cm_names)) %>%
  as.data.frame()

rownames(mean_mat) <- mean_mat$disease
mean_mat$disease <- NULL

mean_mat <- as.matrix(mean_mat)
mean_mat <- mean_mat[
  disease_order[disease_order %in% rownames(mean_mat)],
  cm_names,
  drop = FALSE
]

# Same Ro/e logic as current Fig.2e.
mat_prop <- mean_mat / rowSums(mean_mat, na.rm = TRUE)

row_total <- rowSums(mat_prop, na.rm = TRUE)
col_total <- colSums(mat_prop, na.rm = TRUE)
grand_total <- sum(mat_prop, na.rm = TRUE)

expected <- outer(row_total, col_total, FUN = "*") / grand_total
rownames(expected) <- rownames(mat_prop)
colnames(expected) <- colnames(mat_prop)

roe <- mat_prop / expected
roe[!is.finite(roe)] <- NA

mean_long <- as.data.frame(as.table(mean_mat), stringsAsFactors = FALSE) %>%
  dplyr::rename(
    disease = Var1,
    Cellular_module = Var2,
    mean_CM_abundance = Freq
  )

expected_long <- as.data.frame(as.table(expected), stringsAsFactors = FALSE) %>%
  dplyr::rename(
    disease = Var1,
    Cellular_module = Var2,
    expected_value = Freq
  )

roe_long <- as.data.frame(as.table(roe), stringsAsFactors = FALSE) %>%
  dplyr::rename(
    disease = Var1,
    Cellular_module = Var2,
    roe = Freq
  )

dominant_cm_df <- roe_long %>%
  dplyr::group_by(disease) %>%
