meta_frac <- meta_use %>%
  dplyr::mutate(
    unit_id = paste0(dataset_id, "__", patient_id),
    majorCluster = as.character(majorCluster)
  ) %>%
  dplyr::filter(majorCluster %in% level1_order)

level1_keep <- level1_order[level1_order %in% unique(meta_frac$majorCluster)]

total_df <- meta_frac %>%
  dplyr::count(
    unit_id,
    patient_id,
    dataset_id,
    disease,
    disease_group,
    name = "total_PBMC_count"
  )

count_df <- meta_frac %>%
  dplyr::count(
    unit_id,
    patient_id,
    dataset_id,
    disease,
    disease_group,
    majorCluster,
    name = "cell_count"
  )

table_s6 <- total_df %>%
  tidyr::expand(
    tidyr::nesting(
      unit_id,
      patient_id,
      dataset_id,
      disease,
      disease_group,
      total_PBMC_count
    ),
    Level1_cell_type = level1_keep
  ) %>%
  dplyr::left_join(
    count_df %>%
      dplyr::rename(Level1_cell_type = majorCluster),
    by = c(
      "unit_id", "patient_id", "dataset_id",
      "disease", "disease_group", "Level1_cell_type"
    )
  ) %>%
  dplyr::mutate(
    cell_count = tidyr::replace_na(cell_count, 0L),
    fraction_percent = cell_count / total_PBMC_count * 100,
    log10_fraction_percent = log10(pmax(fraction_percent, 1e-3)),
    disease = as.character(disease),
    disease_group = as.character(disease_group)
  )

p_table_s6 <- table_s6 %>%
  dplyr::group_by(Level1_cell_type) %>%
  dplyr::summarise(
    p_value = tryCatch(
      stats::kruskal.test(fraction_percent ~ disease)$p.value,
      error = function(e) NA_real_
    ),
    .groups = "drop"
  ) %>%
  dplyr::mutate(
    adjusted_p_value = p.adjust(p_value, method = "BH")
  )

table_s6 <- table_s6 %>%
  dplyr::left_join(p_table_s6, by = "Level1_cell_type") %>%
  dplyr::arrange(
    factor(disease, levels = disease_order),
    dataset_id,
    patient_id,
    factor(Level1_cell_type, levels = level1_order)
  )

write.csv(
