# Level 2 Ro/e within each Level 1 compartment.
# This matches the logic of Level 2 disease preference plots.
MIN_LEVEL2_TOTAL <- 30
MIN_LEVEL2_DISEASE_COUNT_FOR_ROE <- 3

level2_parent_list <- level1_order[level1_order %in% unique(meta_use$majorCluster)]

table_s5_l2 <- lapply(level2_parent_list, function(parent_ct) {

  df_parent <- meta_use %>%
    dplyr::filter(majorCluster == parent_ct)

  keep_sub <- df_parent %>%
    dplyr::count(subCluster, name = "n_total") %>%
    dplyr::filter(n_total >= MIN_LEVEL2_TOTAL) %>%
    dplyr::pull(subCluster)

  df_parent <- df_parent %>%
    dplyr::filter(subCluster %in% keep_sub)

  compute_roe_table(
    df = df_parent,
    cell_col = "subCluster",
    annotation_level = "Level 2",
    parent_level1_value = parent_ct,
    min_cell_per_group = MIN_LEVEL2_DISEASE_COUNT_FOR_ROE
  )
}) %>%
  dplyr::bind_rows()

table_s5 <- dplyr::bind_rows(table_s5_l1, table_s5_l2)

