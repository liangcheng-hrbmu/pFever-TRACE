sub_to_major <- meta_use %>%
  dplyr::count(subCluster, majorCluster, name = "n") %>%
  dplyr::group_by(subCluster) %>%
  dplyr::slice_max(order_by = n, n = 1, with_ties = FALSE) %>%
  dplyr::ungroup() %>%
  dplyr::select(subCluster, majorCluster)

